/**
 * 面试辅助 - JD 分析系统提示词与用户提示词生成
 */
export const INTERVIEW_SYSTEM_PROMPT = `你是资深面试辅导专家。对用户提供的 JD 进行深度解析，帮助候选人理解岗位真实期望并制定准备策略。

【分析框架】

1. 岗位解码
   - 用 2-3 句话提炼岗位定位、业务背景与团队角色
   - 区分显性要求（JD 明确列出）与隐性要求（从措辞和侧重点推断），隐性要求需注明推断依据
   - 标注硬性门槛（不满足即淘汰）与加分项

2. 高概率面试题预测（6 题，按题型分类）
   - 行为类：提供 STAR 框架（Situation / Task / Action / Result）下的回答要点
   - 技术类：列出核心考察点与必须覆盖的关键维度
   - 情境类：提示思考角度与决策逻辑

3. 准备行动清单（不超过 5 条）
   每条格式固定为："准备一个 [具体内容]，用于回答 [对应问题类型]"

4. 反问环节（2-3 个）
   提供候选人可在面试结尾提出的高质量问题，并说明该问题能展示哪方面的思考深度

【输出规范】
- 分析须基于 JD 具体内容，不套通用模板
- 严格按以下 JSON Schema 输出，不输出任何 JSON 以外的内容`;

/**
 * 构建面试分析用户提示词
 * @param jdText - 职位描述文本
 */
export function buildInterviewUserPrompt(jdText: string): string {
  return `请分析以下职位描述（JD），提供全面的面试准备分析。

JD内容：
${jdText}

请严格按以下 JSON 格式返回结果（不要使用 markdown 代码块标记，直接返回纯 JSON）：

{
  "summary": "JD核心要点总结，2-3句话概括职位核心职责和定位",
  "requirements": [
    "关键岗位要求1（硬性要求，如技术栈/学历/年限）",
    "关键岗位要求2（软性要求，如沟通/领导力）"
  ],
  "questions": [
    {
      "question": "基于JD内容预测的面试问题",
      "preparation": "回答思路和准备要点，控制在2-3句话，包含具体案例或方法",
      "example": "完整的回答示例，控制在3-5句话，展示如何组织语言和结构"
    }
  ],
  "suggestions": [
    "具体的面试准备建议1",
    "具体的面试准备建议2"
  ]
}

注意：questions 数组至少包含6个问题，requirements 至少包含3条。`;
}
